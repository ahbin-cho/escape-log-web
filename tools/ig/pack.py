WD = "월화수목금토일"

def with_weekday(name):
    """'08_11-20_스토리_…' → '08_11-20(금)_스토리_…' (괄호 요일은 날짜로 다시 계산)"""
    m = re.match(r"(\d+[a-z]?)_(\d+)-(\d+)(\([^)]*\))?_(.*)", name)
    if not m: return name
    n, mo, dd, _, rest = m.groups()
    wd = WD[datetime.date(2026, int(mo), int(dd)).weekday()]
    return f"{n}_{mo}-{dd}({wd})_{rest}"

