def main(reel_path):
    root = os.path.join(OUT, "방탈로그_직접올리기")
    shutil.rmtree(root, ignore_errors=True)
    jobs = []
    for p in POSTS:
        d = os.path.join(root, p["dir"]); os.makedirs(d, exist_ok=True)
        for i, html in enumerate(p.get("pages", []), 1):
            w, h = p["size"]
            jobs.append({"html": html, "out": os.path.join(d, f"{i}.jpg"), "w": w, "h": h})
        if p.get("video") == "REEL" and reel_path:
            shutil.copy(reel_path, os.path.join(d, "종이인형극.mp4"))
        if p.get("caption"):
            open(os.path.join(d, "캡션.txt"), "w").write(p["caption"] + "\n")
        open(os.path.join(d, "올리는법.txt"), "w").write(p["how"] + "\n")
    open(os.path.join(root, "00_일정표.txt"), "w").write(SCHEDULE)
    jf = os.path.join(OUT, "jobs.json"); json.dump(jobs, open(jf, "w"), ensure_ascii=False)
    subprocess.run(["node", "tools/ig/render.cjs", jf], check=True)
    z = shutil.make_archive(os.path.join(OUT, "방탈로그_직접올리기"), "zip", OUT, "방탈로그_직접올리기")
    print(z)

if __name__ == "__main__":
    main(sys.argv[2] if len(sys.argv) > 2 else None)
