-- 셜록홈즈 32곳 예약 오픈: "몇 달 앞까지 열려 있음"
-- Supabase → SQL Editor 에 붙여 넣고 Run. 여러 번 실행해도 안전(비어 있는 곳만 채운다).
-- 출처: 셜록홈즈 공식 예약 페이지 지점별 시간표(sherlock-holmes.co.kr/reservation/res_schedule.php, 2026-11-13 확인)
--   2주 뒤(11/27)·한 달 뒤(12/13)·두 달 뒤(1/13)·넉 달 뒤(2027-03-13) 모두 '예약가능' 시간이 열려 있는 곳만 넣었다.
--   → "N일 전" 규칙이 없는 곳. 사이트에는 "원하는 날짜를 지금 바로 예약할 수 있어요"로 보인다.
-- 넣지 않은 곳:
--   셜록홈즈 부산기장정관점: 홈페이지 공지 "2024년 1월부터 '네이버예약'으로 변경" → 네이버 예약에서 따로 확인 필요
--   매장 이름이 '셜록홈즈'뿐인 행: 지점을 알 수 없음
--   이미 값이 있는 곳(대전둔산·대전은행·안양범계·광명철산·잠실새내 = 14일 전, 수원 3곳)은 그대로

update public.catalog set booking_open = '몇 달 앞까지 열려 있음'
where coalesce(booking_open, '') = ''
  and cafe in (
  '셜록홈즈 구리점',
