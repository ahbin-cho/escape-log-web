  '셜록홈즈 뉴안양점',
  '셜록홈즈 대구동성로점',
  '셜록홈즈 대학로점',
  '셜록홈즈 동탄점',
  '셜록홈즈 미사점',
  '셜록홈즈 부산 아트몰링',
  '셜록홈즈 부천중동점',
  '셜록홈즈 부평2호점',
  '셜록홈즈 부평점',
